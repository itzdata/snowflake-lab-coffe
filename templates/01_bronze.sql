USE ROLE COFFEE_LAB_PARTICIPANT;
USE WAREHOUSE COMPUTE_WH;

CREATE SCHEMA IF NOT EXISTS COFFEE_BRONZE.{{INI}}_{{FUENTE}}
  COMMENT = 'Bronze de {{FUENTE}} | owner: {{OWNER}} | fuente: {{FUENTE}}';

LIST @COFFEE_BRONZE.LANDING.STG_DATASETS/{{fuente}}/;

-- CSV / Parquet: tabla a partir del esquema inferido
CREATE OR REPLACE TABLE COFFEE_BRONZE.{{INI}}_{{FUENTE}}.RAW_{{ENTIDAD}}
  USING TEMPLATE (
    SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) WITHIN GROUP (ORDER BY ORDER_ID)
    FROM TABLE(INFER_SCHEMA(
      LOCATION    => '@COFFEE_BRONZE.LANDING.STG_DATASETS/{{fuente}}/{{archivo}}',
      FILE_FORMAT => 'COFFEE_BRONZE.LANDING.FF_CSV',
      IGNORE_CASE => TRUE))
  );

ALTER TABLE COFFEE_BRONZE.{{INI}}_{{FUENTE}}.RAW_{{ENTIDAD}} ADD COLUMN
  _FILE_NAME STRING, _FILE_ROW NUMBER, _LOADED_TS TIMESTAMP_LTZ;

COPY INTO COFFEE_BRONZE.{{INI}}_{{FUENTE}}.RAW_{{ENTIDAD}}
  FROM @COFFEE_BRONZE.LANDING.STG_DATASETS/{{fuente}}/{{archivo}}
  FILE_FORMAT = (FORMAT_NAME = 'COFFEE_BRONZE.LANDING.FF_CSV')
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
  INCLUDE_METADATA = (_FILE_NAME = METADATA$FILENAME, _FILE_ROW = METADATA$FILE_ROW_NUMBER, _LOADED_TS = METADATA$START_SCAN_TIME)
  ON_ERROR = CONTINUE;

COMMENT ON TABLE COFFEE_BRONZE.{{INI}}_{{FUENTE}}.RAW_{{ENTIDAD}} IS 'Carga cruda de {{archivo}} | owner: {{OWNER}} | fuente: {{FUENTE}}';

