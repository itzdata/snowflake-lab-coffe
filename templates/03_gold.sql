USE ROLE COFFEE_LAB_PARTICIPANT;
USE WAREHOUSE COMPUTE_WH;

CREATE SCHEMA IF NOT EXISTS COFFEE_GOLD.{{INI}}_{{FUENTE}}
  COMMENT = 'Gold de {{FUENTE}} | owner: {{OWNER}} | fuente: {{FUENTE}}';

-- 1. Agregados
CREATE OR REPLACE DYNAMIC TABLE COFFEE_GOLD.{{INI}}_{{FUENTE}}.AGG_SALES_DAILY_STORE
  TARGET_LAG = '24 hours' WAREHOUSE = COMPUTE_WH
  COMMENT = 'Ventas diarias por tienda y categoría | owner: {{OWNER}} | fuente: {{FUENTE}}'
AS
SELECT F.ORDER_DATE, F.STORE_ID, P.CATEGORY_NAME,
       COUNT(DISTINCT F.ORDER_ID) AS ORDER_CNT, SUM(F.ITEM_QTY) AS ITEM_QTY, SUM(F.TOTAL_AMT) AS TOTAL_AMT,
       SUM(F.TOTAL_AMT) / NULLIF(COUNT(DISTINCT F.ORDER_ID), 0) AS AVG_TICKET_AMT
FROM COFFEE_SILVER.{{INI}}_{{FUENTE}}.FCT_SALES F
JOIN COFFEE_SILVER.{{INI}}_{{FUENTE}}.DIM_PRODUCT P ON P.PRODUCT_SK = F.PRODUCT_SK
GROUP BY ALL;

-- 2. KPIs
CREATE OR REPLACE VIEW COFFEE_GOLD.{{INI}}_{{FUENTE}}.KPI_SALES
  COMMENT = 'KPIs de ventas por mes | owner: {{OWNER}} | fuente: {{FUENTE}}'
AS
SELECT DATE_TRUNC(MONTH, ORDER_DATE) AS MONTH_DATE,
       SUM(TOTAL_AMT) AS TOTAL_AMT, SUM(ORDER_CNT) AS ORDER_CNT,
       SUM(TOTAL_AMT) / NULLIF(SUM(ORDER_CNT), 0) AS AVG_TICKET_AMT,
       TOTAL_AMT / NULLIF(LAG(TOTAL_AMT) OVER (ORDER BY MONTH_DATE), 0) - 1 AS GROWTH_PCT
FROM COFFEE_GOLD.{{INI}}_{{FUENTE}}.AGG_SALES_DAILY_STORE
GROUP BY ALL;

-- 3. Semantic view
CREATE OR REPLACE SEMANTIC VIEW COFFEE_GOLD.{{INI}}_{{FUENTE}}.SV_{{FUENTE}}
  TABLES (
    SALES    AS COFFEE_SILVER.{{INI}}_{{FUENTE}}.FCT_SALES PRIMARY KEY (ORDER_ID, PRODUCT_SK) COMMENT = 'Líneas de venta',
    PRODUCTS AS COFFEE_SILVER.{{INI}}_{{FUENTE}}.DIM_PRODUCT PRIMARY KEY (PRODUCT_SK) WITH SYNONYMS = ('artículos') COMMENT = 'Productos'
  )
  RELATIONSHIPS ( SALES_TO_PRODUCT AS SALES (PRODUCT_SK) REFERENCES PRODUCTS )
  DIMENSIONS (
    SALES.ORDER_DATE AS ORDER_DATE WITH SYNONYMS = ('fecha') COMMENT = 'Fecha de la orden',
    SALES.STORE_ID   AS STORE_ID   WITH SYNONYMS = ('tienda','sucursal'),
    PRODUCTS.PRODUCT_NAME AS PRODUCT_NAME WITH SYNONYMS = ('producto'),
    PRODUCTS.CATEGORY_NAME AS CATEGORY_NAME WITH SYNONYMS = ('categoría')
  )
  METRICS (
    SALES.TOTAL_SALES AS SUM(TOTAL_AMT) WITH SYNONYMS = ('ventas','ingresos') COMMENT = 'Ventas totales',
    SALES.ORDERS      AS COUNT(DISTINCT ORDER_ID) WITH SYNONYMS = ('órdenes','pedidos'),
    SALES.UNITS       AS SUM(ITEM_QTY) WITH SYNONYMS = ('unidades')
  )
  COMMENT = 'Semantic view de {{FUENTE}} | owner: {{OWNER}} | fuente: {{FUENTE}}';

-- Validación
SELECT * FROM SEMANTIC_VIEW(COFFEE_GOLD.{{INI}}_{{FUENTE}}.SV_{{FUENTE}}
  DIMENSIONS PRODUCTS.CATEGORY_NAME METRICS SALES.TOTAL_SALES) ORDER BY TOTAL_SALES DESC;

SELECT (SELECT SUM(TOTAL_AMT) FROM COFFEE_SILVER.{{INI}}_{{FUENTE}}.FCT_SALES)
     - (SELECT SUM(TOTAL_AMT) FROM COFFEE_GOLD.{{INI}}_{{FUENTE}}.AGG_SALES_DAILY_STORE) AS DIFERENCIA_DEBE_SER_0;

