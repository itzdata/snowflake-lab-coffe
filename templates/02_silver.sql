USE ROLE COFFEE_LAB_PARTICIPANT;
USE WAREHOUSE COMPUTE_WH;

CREATE SCHEMA IF NOT EXISTS COFFEE_SILVER.{{INI}}_{{FUENTE}}
  COMMENT = 'Silver de {{FUENTE}} | owner: {{OWNER}} | fuente: {{FUENTE}}';

-- 1. STG_: tipado, limpieza, deduplicación (dynamic table)
CREATE OR REPLACE DYNAMIC TABLE COFFEE_SILVER.{{INI}}_{{FUENTE}}.STG_ORDERS
  TARGET_LAG = '24 hours' WAREHOUSE = COMPUTE_WH
  COMMENT = 'Órdenes tipadas y deduplicadas | owner: {{OWNER}} | fuente: {{FUENTE}}'
AS
SELECT
  TRY_TO_NUMBER(ORDER_ID)                 AS ORDER_ID,
  TRY_TO_DATE(ORDER_DATE)                 AS ORDER_DATE,
  UPPER(NULLIF(TRIM(STORE_ID), ''))       AS STORE_ID,
  UPPER(NULLIF(TRIM(PRODUCT_ID), ''))     AS PRODUCT_ID,
  TRY_TO_NUMBER(QUANTITY)                 AS ITEM_QTY,
  TRY_TO_DECIMAL(UNIT_PRICE, 12, 2)       AS UNIT_PRICE_AMT,
  ITEM_QTY * UNIT_PRICE_AMT               AS TOTAL_AMT,
  _LOADED_TS,
  CURRENT_TIMESTAMP()                     AS _UPDATED_TS
FROM COFFEE_BRONZE.{{INI}}_{{FUENTE}}.RAW_ORDERS
QUALIFY ROW_NUMBER() OVER (PARTITION BY ORDER_ID, PRODUCT_ID ORDER BY _LOADED_TS DESC) = 1;

-- 2. (Sin enriquecimiento IA — ver standards/ai_functions.md)

-- 3. Dimensiones
CREATE OR REPLACE TABLE COFFEE_SILVER.{{INI}}_{{FUENTE}}.DIM_PRODUCT
  COMMENT = 'Dimensión producto | owner: {{OWNER}} | fuente: {{FUENTE}}'
AS
SELECT HASH(UPPER(TRIM(PRODUCT_ID))) AS PRODUCT_SK, UPPER(TRIM(PRODUCT_ID)) AS PRODUCT_ID,
       INITCAP(TRIM(PRODUCT_NAME)) AS PRODUCT_NAME, INITCAP(TRIM(CATEGORY)) AS CATEGORY_NAME
FROM COFFEE_BRONZE.{{INI}}_{{FUENTE}}.RAW_PRODUCTS
QUALIFY ROW_NUMBER() OVER (PARTITION BY UPPER(TRIM(PRODUCT_ID)) ORDER BY _LOADED_TS DESC) = 1;

CREATE OR REPLACE TABLE COFFEE_SILVER.{{INI}}_{{FUENTE}}.DIM_DATE
  COMMENT = 'Dimensión fecha | owner: {{OWNER}} | fuente: {{FUENTE}}'
AS
WITH R AS (SELECT MIN(ORDER_DATE) D0, MAX(ORDER_DATE) D1 FROM COFFEE_SILVER.{{INI}}_{{FUENTE}}.STG_ORDERS)
SELECT DATEADD(DAY, SEQ4(), R.D0) AS DATE_KEY,
       YEAR(DATE_KEY) AS YEAR_NUM, MONTH(DATE_KEY) AS MONTH_NUM, MONTHNAME(DATE_KEY) AS MONTH_NAME,
       DAYOFWEEKISO(DATE_KEY) AS WEEKDAY_NUM, DAYNAME(DATE_KEY) AS WEEKDAY_NAME,
       DAYOFWEEKISO(DATE_KEY) IN (6,7) AS IS_WEEKEND
FROM R, TABLE(GENERATOR(ROWCOUNT => 3660))
QUALIFY DATE_KEY <= R.D1;

-- 4. Hechos
CREATE OR REPLACE TABLE COFFEE_SILVER.{{INI}}_{{FUENTE}}.FCT_SALES
  COMMENT = 'Hecho ventas, grano: línea de orden | owner: {{OWNER}} | fuente: {{FUENTE}}'
AS
SELECT O.ORDER_ID, O.ORDER_DATE, P.PRODUCT_SK, O.STORE_ID, O.ITEM_QTY, O.UNIT_PRICE_AMT, O.TOTAL_AMT
FROM COFFEE_SILVER.{{INI}}_{{FUENTE}}.STG_ORDERS O
LEFT JOIN COFFEE_SILVER.{{INI}}_{{FUENTE}}.DIM_PRODUCT P ON P.PRODUCT_ID = O.PRODUCT_ID;

-- Validaciones
SELECT 'DIM_PRODUCT unicidad' CHECK_NAME, COUNT(*) - COUNT(DISTINCT PRODUCT_ID) AS FALLAS FROM COFFEE_SILVER.{{INI}}_{{FUENTE}}.DIM_PRODUCT
UNION ALL
SELECT 'FCT_SALES sin producto', COUNT_IF(PRODUCT_SK IS NULL) FROM COFFEE_SILVER.{{INI}}_{{FUENTE}}.FCT_SALES;
