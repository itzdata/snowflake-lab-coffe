USE ROLE ACCOUNTADMIN;

-- 1. Bases de datos (una por capa, compartidas por todos los participantes)
CREATE DATABASE IF NOT EXISTS COFFEE_BRONZE COMMENT = 'Capa Bronze: copia fiel de los archivos fuente';
CREATE DATABASE IF NOT EXISTS COFFEE_SILVER COMMENT = 'Capa Silver: datos limpios, tipados y modelo dimensional';
CREATE DATABASE IF NOT EXISTS COFFEE_GOLD   COMMENT = 'Capa Gold: métricas, semantic views, agentes y dashboards';

-- 2. Zona de aterrizaje compartida
CREATE SCHEMA IF NOT EXISTS COFFEE_BRONZE.LANDING COMMENT = 'Stage y file formats compartidos (solo lectura para participantes)';

CREATE STAGE IF NOT EXISTS COFFEE_BRONZE.LANDING.STG_DATASETS
  DIRECTORY = (ENABLE = TRUE)
  ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE')
  COMMENT = 'Datasets del laboratorio. Una carpeta por fuente: @STG_DATASETS/<fuente>/';

CREATE FILE FORMAT IF NOT EXISTS COFFEE_BRONZE.LANDING.FF_CSV
  TYPE = CSV PARSE_HEADER = TRUE FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  NULL_IF = ('', 'NULL', 'null') EMPTY_FIELD_AS_NULL = TRUE ENCODING = 'UTF8'
  ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE
  COMMENT = 'CSV con encabezado (usar con INFER_SCHEMA / MATCH_BY_COLUMN_NAME)';

CREATE FILE FORMAT IF NOT EXISTS COFFEE_BRONZE.LANDING.FF_JSON
  TYPE = JSON STRIP_OUTER_ARRAY = TRUE COMMENT = 'JSON / NDJSON';

CREATE FILE FORMAT IF NOT EXISTS COFFEE_BRONZE.LANDING.FF_PARQUET
  TYPE = PARQUET COMMENT = 'Parquet';

-- 3. Rol de participante
CREATE ROLE IF NOT EXISTS COFFEE_LAB_PARTICIPANT COMMENT = 'Participantes del laboratorio Coffee Medallion';
GRANT ROLE COFFEE_LAB_PARTICIPANT TO ROLE SYSADMIN;

GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE COFFEE_LAB_PARTICIPANT;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE COFFEE_LAB_PARTICIPANT;

GRANT USAGE, CREATE SCHEMA ON DATABASE COFFEE_BRONZE TO ROLE COFFEE_LAB_PARTICIPANT;
GRANT USAGE, CREATE SCHEMA ON DATABASE COFFEE_SILVER TO ROLE COFFEE_LAB_PARTICIPANT;
GRANT USAGE, CREATE SCHEMA ON DATABASE COFFEE_GOLD   TO ROLE COFFEE_LAB_PARTICIPANT;

GRANT USAGE ON SCHEMA COFFEE_BRONZE.LANDING TO ROLE COFFEE_LAB_PARTICIPANT;
GRANT READ  ON STAGE  COFFEE_BRONZE.LANDING.STG_DATASETS TO ROLE COFFEE_LAB_PARTICIPANT;
GRANT USAGE ON ALL FILE FORMATS IN SCHEMA COFFEE_BRONZE.LANDING TO ROLE COFFEE_LAB_PARTICIPANT;

